import { mkdtemp, mkdir, readFile, rm, symlink, writeFile, lstat } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { digestTree, sha256 } from "./provider-candidate-build-tree.mjs";
import { buildEnvironment, execFileAsync } from "./provider-candidate-source.mjs";

const PACKAGES = Object.freeze([
  "packages/platform/filesystem-custody",
  "packages/contexts/agent-execution",
]);
const COMMANDS = Object.freeze([
  ["node", "node_modules/typescript/bin/tsc", "--project", `${PACKAGES[0]}/tsconfig.json`, "--pretty", "false"],
  ["node", "scripts/build-native-helper.mjs"],
  ["node", "node_modules/typescript/bin/tsc", "--project", `${PACKAGES[1]}/tsconfig.json`, "--pretty", "false"],
]);

const dependencyRoots = async root => {
  const paths = [];
  for (const path of ["node_modules", ...PACKAGES.map(pkg => `${pkg}/node_modules`)]) {
    try {await lstat(join(root, path)); paths.push(path);} catch (error) {
      if (error.code !== "ENOENT" || path === "node_modules") {throw error;}
    }
  }
  return paths;
};

export const installedClosureDigest = async root => {
  const entries = [];
  for (const path of await dependencyRoots(root)) {
    entries.push([path, await digestTree(join(root, path), root)]);
  }
  return sha256(JSON.stringify(entries));
};

export const executedBuildIdentity = async root => {
  const trees = [];
  for (const pkg of PACKAGES) {trees.push([pkg, await digestTree(join(root, pkg, "dist"))]);}
  return Object.freeze({
    bytes: trees.reduce((sum, [, tree]) => sum + tree.bytes, 0),
    files: trees.reduce((sum, [, tree]) => sum + tree.files, 0),
    treeDigest: sha256(JSON.stringify(trees)),
  });
};

const copyBuildSources = async (snapshot, target) => {
  for (const [path, file] of snapshot.files) {
    if (!PACKAGES.some(pkg => path.startsWith(`${pkg}/`)) &&
        !["package.json", "pnpm-lock.yaml", "pnpm-workspace.yaml", "architecture/foundation/scaffold-tsconfig.json"].includes(path)) {continue;}
    // Even accidentally tracked outputs cannot seed this clean build.
    if (/(?:^|\/)(?:dist|node_modules|\.cache)(?:\/|$)/u.test(path) || path.endsWith(".tsbuildinfo")) {continue;}
    await mkdir(dirname(join(target, path)), {recursive: true});
    await writeFile(join(target, path), file.bytes, {mode: file.mode});
  }
  for (const path of await dependencyRoots(snapshot.root)) {
    await mkdir(dirname(join(target, path)), {recursive: true});
    await symlink(join(snapshot.root, path), join(target, path), "dir");
  }
};

// Trust boundary: a local offline compiler/toolchain in a cooperative checkout.
// No serialized caller receipt, callback, build timestamp, or existing dist can
// mint this receipt. Empty temporary outputs must be generated by these commands
// and match BOTH executed workspace packages byte-for-byte. Installed dependency
// bytes and links are checked before/after and on evidence publication.
export const verifyCleanBuild = async snapshot => {
  for (const required of ["pnpm-lock.yaml", "pnpm-workspace.yaml", "package.json"]) {
    if (!snapshot.files.has(required)) {throw new Error("clean build requires package and dependency authority");}
  }
  const dependenciesDigest = await installedClosureDigest(snapshot.root);
  const executed = await executedBuildIdentity(snapshot.root);
  const nodeDigest = sha256(await readFile(process.execPath));
  const root = await mkdtemp(join(tmpdir(), "ar-provider-clean-build-"));
  try {
    await copyBuildSources(snapshot, root);
    for (const [index, command] of COMMANDS.entries()) {
      try {
        await execFileAsync(process.execPath, command.slice(1), {
          cwd: index === 1 ? join(root, PACKAGES[0]) : root,
          env: buildEnvironment, timeout: 120_000, maxBuffer: 1024 ** 2,
        });
      } catch {throw new Error("trusted offline clean build failed");}
      if (index === 1) {
        const clean = await digestTree(join(root, PACKAGES[0], "dist"));
        const actual = await digestTree(join(snapshot.root, PACKAGES[0], "dist"));
        if (clean.treeDigest !== actual.treeDigest) {throw new Error("executed dependency build differs from clean build");}
      }
    }
    const clean = await executedBuildIdentity(root);
    if (clean.treeDigest !== executed.treeDigest) {throw new Error("executed build differs from clean build");}
    if (dependenciesDigest !== await installedClosureDigest(snapshot.root) ||
        executed.treeDigest !== (await executedBuildIdentity(snapshot.root)).treeDigest ||
        nodeDigest !== sha256(await readFile(process.execPath))) {
      throw new Error("build inputs changed during clean build verification");
    }
    return Object.freeze({
      ...executed, dependenciesDigest,
      commandDigest: sha256(JSON.stringify(COMMANDS)),
      nodeDigest,
      profile: "local-offline-clean-build/v1",
    });
  } finally {await rm(root, {recursive: true, force: true});}
};
